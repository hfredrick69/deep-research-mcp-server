interface ReportDir {
  dir: string;
  writeReport(content: string, name?: string): string;
  cleanup(): void;
}

function makeReportDir(prefix = 'deep-research-server-test-'): ReportDir {
  const dir = path.resolve(fs.mkdtempSync(path.join(os.tmpdir(), prefix)));
  return {
    dir,
    writeReport(content, name = 'deep_research_report.md') {
      const p = path.join(dir, name);
      fs.writeFileSync(p, content, 'utf8');
      return p;
    },
    cleanup() {
      const tmpRoot = path.resolve(os.tmpdir());
      assert.ok(
        dir.startsWith(tmpRoot + path.sep) && path.basename(dir).startsWith(prefix),
        `refusing to delete unexpected directory ${dir}`,
      );
      fs.rmSync(dir, { recursive: true, force: true });
    },
  };
}

async function connect(deps: ServerDeps): Promise<{ client: Client; close: () => Promise<void> }> {
  const server = createServer(deps);
  const [clientTransport, serverTransport] = InMemoryTransport.createLinkedPair();
  const client = new Client({ name: 'server-test', version: '0.0.0' });
  await server.connect(serverTransport);
  await client.connect(clientTransport);
  return {
    client,
    close: async () => {
      await client.close();
      await server.close();
    },
  };
}

async function callRun(client: Client, args: Record<string, unknown>, options?: Parameters<Client['callTool']>[2]): Promise<MCPResearchResult> {
  const result = await client.callTool({ name: 'deepResearch.run', arguments: args }, undefined, options);
  return result as unknown as MCPResearchResult;
}

function textOf(result: MCPResearchResult): string {
  return result.content.map(part => part.text).join('\n');
}

const tick = (): Promise<void> => new Promise(resolve => setTimeout(resolve, 0));

interface LogData { requestId: string; stage: string; elapsedMs: number; message: string }
interface LogParams { level: string; logger?: string; data: LogData }

function collectLogs(client: Client): LogParams[] {
  const logs: LogParams[] = [];
  client.setNotificationHandler(LoggingMessageNotificationSchema, (n) => {
    logs.push(n.params as unknown as LogParams);
  });
  return logs;
}

