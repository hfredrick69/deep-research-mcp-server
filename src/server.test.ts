test('stdio switches to file mode only when the inline text exceeds the byte limit', async () => {
  const reportDir = makeReportDir();
  const prefix = '# T\n\nintro.\n\n';
  const cases: Array<{ name: string; delta: number; file: boolean }> = [
    { name: 'under', delta: -1, file: false },
    { name: 'equal', delta: 0, file: false },
    { name: 'over', delta: 1, file: true },
  ];
  try {
    for (const c of cases) {
      const report = prefix + 'z'.repeat(400 + c.delta - HEADING_BYTES - Buffer.byteLength(prefix));
      assert.equal(Buffer.byteLength(`${RESULT_HEADING}\n\n${report}`), 400 + c.delta);
      const reportPath = reportDir.writeReport(report, `${c.name}.md`);
      const stub = stubResearch(async () => ({ learnings: ['l1'], visitedUrls: ['https://example.test/a'], content: report, reportPath }));
      const { client, close } = await connect({
        env: { ...GEMINI_ENV, MCP_STDIO_INLINE_MAX_BYTES: '400' },
        research: stub.fn,
        cache: freshCache(),
        cwd: () => reportDir.dir,
      });
      try {
        const result = await callRun(client, { query: `threshold-${c.name}` });
        const text = textOf(result);
        assert.ok(text.startsWith(RESULT_HEADING), c.name);
        if (c.file) {
          assert.ok(text.includes(`**Report file:** ${JSON.stringify(reportPath)}`), `${c.name}: ${text}`);
          assert.ok(!text.includes('z'.repeat(100)), `${c.name}: body not inlined`);
        } else {
          assert.ok(text.endsWith(report), `${c.name}: full report inline`);
          assert.ok(!text.includes('**Report file:**'), c.name);
        }
        assert.equal(result.metadata.reportSizeBytes, Buffer.byteLength(report), c.name);
        assert.equal(result.metadata.reportPath, reportPath, c.name);
        assert.equal(result.isError, undefined, c.name);
      } finally {
        await close();
      }
    }
  } finally {
    reportDir.cleanup();
  }
});

