test('inspectReportFile distinguishes a readable regular file from missing, directory and unreadable paths', () => {
  const reportDir = makeReportDir();
  try {
    const p = reportDir.writeReport('hello', 'ok.md');
    assert.deepEqual(inspectReportFile(p), { ok: true, sizeBytes: 5 });
    assert.deepEqual(inspectReportFile(path.join(reportDir.dir, 'missing.md')), { ok: false, reason: 'missing' });
    assert.deepEqual(inspectReportFile(reportDir.dir), { ok: false, reason: 'not_a_file' });
    // A symlink inside the launch directory is never followed, even when it points at a regular file.
    const link = path.join(reportDir.dir, 'link.md');
    fs.symlinkSync(p, link);
    assert.deepEqual(inspectReportFile(link), { ok: false, reason: 'not_a_file' });
    // A FIFO must be rejected without opening it (opening a FIFO read-only blocks until a writer appears).
    const fifo = path.join(reportDir.dir, 'pipe.md');
    execFileSync('mkfifo', [fifo]);
    assert.deepEqual(inspectReportFile(fifo), { ok: false, reason: 'not_a_file' });
  } finally {
    reportDir.cleanup();
  }
});

