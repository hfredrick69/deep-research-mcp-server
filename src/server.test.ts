test('heartbeats every 30 s with the latest phase and monotonic elapsed time, and clears timers on completion', async () => {
  let clock = 0;
  const timers = new Map<number, { cb: () => void; at: number }>();
  let nextId = 1;
  const setTimer = (cb: () => void, ms: number): unknown => { const id = nextId++; timers.set(id, { cb, at: clock + ms }); return id; };
  const clearTimer = (handle: unknown): void => { timers.delete(handle as number); };
  const fire = (t: number): void => {
    clock = t;
    for (const [id, timer] of [...timers]) {
      if (timer.at <= clock) { timers.delete(id); timer.cb(); }
    }
  };
  let release!: () => void;
  const released = new Promise<void>(resolve => { release = resolve; });
  const stub = stubResearch(async (options) => {
    await tick();
    options.onProgress?.({ currentDepth: 1, totalDepth: 2, currentBreadth: 1, totalBreadth: 2, totalQueries: 4, completedQueries: 1, currentQuery: 'SECRET' });
    await released;
    return okResult();
  });
  const { client, close } = await connect({ env: GEMINI_ENV, research: stub.fn, cache: freshCache(), now: () => new Date(clock), setTimer, clearTimer });
  try {
    const logs = collectLogs(client);
    const pending = callRun(client, { query: 'heartbeat' });
    for (let i = 0; i < 5 && !logs.some(n => n.data.stage === 'researching'); i += 1) await tick();
    assert.equal(logs[0]!.data.stage, 'starting');
    assert.equal(logs[0]!.data.elapsedMs, 0);
    assert.ok(logs.some(n => n.data.message === 'Researching (depth 1/2, 1/4 queries complete).'), JSON.stringify(logs));
    assert.equal(timers.size, 1, 'one heartbeat timer armed');

    fire(30_000);
    await tick();
    const hb1 = logs.find(n => n.data.stage === 'heartbeat');
    assert.ok(hb1, JSON.stringify(logs));
    assert.equal(hb1.data.message, 'Still researching; 30s elapsed.');
    assert.equal(hb1.data.elapsedMs, 30_000);

    fire(60_000);
    await tick();
    const beats = logs.filter(n => n.data.stage === 'heartbeat');
    assert.equal(beats.length, 2);
    assert.equal(beats[1]!.data.message, 'Still researching; 60s elapsed.');
    assert.equal(beats[1]!.data.elapsedMs, 60_000);

    release();
    const result = await pending;
    assert.equal(result.metadata.errorCategory, undefined);
    assert.equal(logs[logs.length - 1]!.data.stage, 'completed');
    assert.equal(timers.size, 0, 'heartbeat timer cleared');
  } finally {
    await close();
  }
});

