test('readStdioInlineMaxBytes parses bytes strictly', () => {
  assert.equal(DEFAULT_STDIO_INLINE_MAX_BYTES, 32_768);
  assert.equal(readStdioInlineMaxBytes({}), DEFAULT_STDIO_INLINE_MAX_BYTES);
  assert.equal(readStdioInlineMaxBytes({ MCP_STDIO_INLINE_MAX_BYTES: '' }), DEFAULT_STDIO_INLINE_MAX_BYTES);
  assert.equal(readStdioInlineMaxBytes({ MCP_STDIO_INLINE_MAX_BYTES: '   ' }), DEFAULT_STDIO_INLINE_MAX_BYTES);
  assert.equal(readStdioInlineMaxBytes({ MCP_STDIO_INLINE_MAX_BYTES: ' 1024 ' }), 1024);
  assert.equal(readStdioInlineMaxBytes({ MCP_STDIO_INLINE_MAX_BYTES: '0' }), 0);
  assert.equal(readStdioInlineMaxBytes({ MCP_STDIO_INLINE_MAX_BYTES: '9007199254740991' }), Number.MAX_SAFE_INTEGER);
  for (const bad of ['-1', '1.5', '1e3', 'abc', '0x10', '9007199254740992', '12 34', '+5']) {
    assert.throws(
      () => readStdioInlineMaxBytes({ MCP_STDIO_INLINE_MAX_BYTES: bad }),
      (err: unknown) => err instanceof GeminiDeepResearchError && err.category === 'invalid_config' && !err.message.includes(bad),
      `rejects ${JSON.stringify(bad)}`,
    );
  }
});

